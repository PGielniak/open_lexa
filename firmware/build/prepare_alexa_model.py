#!/usr/bin/env python3
"""Reproduce the bundled WakeNet9 Alexa C++ blob from a pinned Espressif revision."""
import hashlib
import json
from pathlib import Path
import struct
import urllib.request

REVISION = '1c0503e7e2dc5e1ecb2fd3da0a5d7e51e3574842'  # ESP-SR v2.0.0
MODEL = 'wn9_alexa'
FILES = ['_MODEL_INFO_', 'wn9_index', 'wn9_data']
firmware = Path(__file__).resolve().parents[1]
out = firmware / 'src/OpenLexaNano/src/model'
out.mkdir(parents=True, exist_ok=True)
base = f'https://raw.githubusercontent.com/espressif/esp-sr/{REVISION}/model/wakenet_model/{MODEL}'
parts = {name: urllib.request.urlopen(f'{base}/{name}', timeout=60).read() for name in FILES}
# Format of Espressif model/pack_model.py. Explicit little endian makes this reproducible.
header_size = 4 + 36 + len(parts) * 40
header = struct.pack('<I32sI', 1, MODEL.encode(), len(parts))
payload = b''
for name, data in parts.items():
    header += struct.pack('<32sII', name.encode(), header_size + len(payload), len(data))
    payload += data
blob = header + payload
assert len(header) == header_size
(out / 'AlexaModel.h').write_text('#pragma once\n#include <cstdint>\nextern const uint8_t kAlexaModel[];\n')
with (out / 'AlexaModel.cpp').open('w') as f:
    f.write('// Generated by firmware/build/prepare_alexa_model.py; see firmware/licenses.\n')
    f.write('#include "AlexaModel.h"\nalignas(16) const uint8_t kAlexaModel[] = {\n')
    for i in range(0, len(blob), 24):
        f.write('  ' + ','.join(f'0x{b:02x}' for b in blob[i:i+24]) + ',\n')
    f.write('};\n')
(out / 'manifest.json').write_text(json.dumps({
    'source': 'https://github.com/espressif/esp-sr', 'revision': REVISION, 'model': MODEL,
    'files': {name: hashlib.sha256(data).hexdigest() for name, data in parts.items()},
    'packed_bytes': len(blob), 'packed_sha256': hashlib.sha256(blob).hexdigest(),
}, indent=2) + '\n')
print(f'Bundled {MODEL}: {len(blob)} bytes')
