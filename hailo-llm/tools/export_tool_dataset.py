"""Export GPT tool-calling decisions as a chat SFT dataset for a local LLM.

Every recording processed by the receiver stores the agent's decision in the
``agent`` column (tool + validated arguments, or ``no_tool``). That decision is
the label; the transcript is the input. When the local Whisper transcript
differs from the GPT one it is added as a second example with the same label,
so the model learns to cope with real local STT errors.

The assistant answer is one JSON line, short on purpose (the Hailo model runs
at a few tokens/s with a 2048-token context)::

    {"name": "play_radio", "arguments": {"station": "Radio Zet"}}
    {"name": null}

Output (``--out``)::

    train.jsonl, test.jsonl   {"messages": [system, user, assistant]}
    system_prompt.txt         the compact tool list; serve the model with exactly this

    uv run python hailo-llm/tools/export_tool_dataset.py --db labels.sqlite3 \\
        --out ~/tool-data --test-days 7 [--extra synthetic.jsonl]

``--extra`` takes ``{"text": ..., "name": ..., "arguments": {...}}`` lines (e.g.
generated by GPT); each is validated against the tool schemas and added to
train only, never to test.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sqlite3

from jsonschema import Draft202012Validator, ValidationError

INSTRUCTION = ('Jesteś polskim asystentem głosowym. Odpowiedz jedną linią JSON: '
               '{"name": "<narzędzie>", "arguments": {...}} albo {"name": null}, gdy wypowiedź '
               'nie jest jednoznaczną prośbą o jedno z narzędzi (szum, rozmowa w tle, inna prośba). '
               'Nie wymyślaj parametrów.')


def default_tools():
    from open_lexa.handlers.sonos.handler import SonosHandler
    return list(SonosHandler.tools)


def system_prompt(tools) -> str:
    lines = [INSTRUCTION, '', 'Narzędzia:']
    for tool in tools:
        props = tool.input_schema.get('properties', {})
        required = set(tool.input_schema.get('required', []))
        args = ', '.join(f'{name}{"" if name in required else "?"}: {spec.get("type", "string")}'
                         for name, spec in props.items())
        lines.append(f'- {tool.name}({args}) — {tool.description}')
    return '\n'.join(lines)


def answer(name, arguments=None) -> str:
    if name is None:
        return json.dumps({'name': None})
    return json.dumps({'name': name, 'arguments': arguments or {}}, ensure_ascii=False)


def label_of(agent: dict):
    """(name, arguments) from a stored agent result, or None when unusable."""
    if agent.get('status') == 'no_tool':
        return None, {}
    executions = agent.get('executions') or []
    if executions and executions[0].get('tool'):
        # A failed *execution* (e.g. Sonos UPnP error) still had a valid, validated call.
        return executions[0]['tool'], executions[0].get('arguments') or {}
    raise ValueError('no tool decision')


def validate(name, arguments, schemas: dict) -> None:
    if name is None:
        return
    if name not in schemas:
        raise ValidationError(f'unknown tool {name!r}')
    Draft202012Validator(schemas[name]).validate(arguments)


def example(system: str, text: str, name, arguments) -> dict:
    return {'messages': [{'role': 'system', 'content': system},
                         {'role': 'user', 'content': text},
                         {'role': 'assistant', 'content': answer(name, arguments)}]}


def build(connection: sqlite3.Connection, tools, *, test_days: int, extra=()) -> dict[str, list]:
    connection.row_factory = sqlite3.Row
    system = system_prompt(tools)
    schemas = {tool.name: dict(tool.input_schema) for tool in tools}
    rows = connection.execute(
        "SELECT recorded_at, corrected_transcript, transcripts, agent FROM recordings "
        "WHERE agent IS NOT NULL AND status != 'skipped' ORDER BY recorded_at, id").fetchall()
    days = sorted({row['recorded_at'][:10] for row in rows})
    # Keep at least the oldest day for training.
    test_days = min(test_days, len(days) - 1)
    test_set = set(days[-test_days:]) if test_days > 0 else set()
    splits: dict[str, list] = {'train': [], 'test': []}
    for row in rows:
        try:
            name, arguments = label_of(json.loads(row['agent']))
            validate(name, arguments, schemas)
        except (ValueError, ValidationError):
            continue
        texts = [row['corrected_transcript']]
        try:
            local = (json.loads(row['transcripts'] or '{}').get('local') or {}).get('text')
        except ValueError:
            local = None
        texts.append(local)
        seen = set()
        split = 'test' if row['recorded_at'][:10] in test_set else 'train'
        for text in texts:
            text = (text or '').strip()
            if text and text.lower() not in seen:
                seen.add(text.lower())
                splits[split].append(example(system, text, name, arguments))
    for item in extra:
        try:
            validate(item.get('name'), item.get('arguments') or {}, schemas)
        except ValidationError:
            continue
        if str(item.get('text') or '').strip():
            splits['train'].append(example(system, item['text'].strip(), item.get('name'),
                                           item.get('arguments')))
    return splits


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--db', type=Path, required=True, help='Admin SQLite label database')
    parser.add_argument('--out', type=Path, required=True)
    parser.add_argument('--test-days', type=int, default=7, help='Newest N recording days go to test')
    parser.add_argument('--extra', type=Path, action='append', default=[],
                        help='Synthetic JSONL {"text","name","arguments"} added to train')
    args = parser.parse_args()
    extra = [json.loads(line) for path in args.extra
             for line in path.read_text(encoding='utf-8').splitlines() if line.strip()]
    tools = default_tools()
    connection = sqlite3.connect(f'file:{args.db}?mode=ro', uri=True)
    try:
        splits = build(connection, tools, test_days=args.test_days, extra=extra)
    finally:
        connection.close()
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / 'system_prompt.txt').write_text(system_prompt(tools) + '\n', encoding='utf-8')
    for name, rows in splits.items():
        (args.out / f'{name}.jsonl').write_text(
            ''.join(json.dumps(row, ensure_ascii=False) + '\n' for row in rows), encoding='utf-8')
    print(', '.join(f'{name}: {len(rows)}' for name, rows in splits.items()), '->', args.out)


if __name__ == '__main__':
    main()
